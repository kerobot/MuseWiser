    /// 左上。
    /// </summary>
    TopLeft,

    /// <summary>
    /// 上中央。
    /// </summary>
    TopCenter,

    /// <summary>
    /// 右上。
    /// </summary>
    TopRight,

    /// <summary>
    /// 左中央。
    /// </summary>
    MiddleLeft,

    /// <summary>
    /// 中央。
    /// </summary>
    MiddleCenter,

    /// <summary>
    /// 右中央。
    /// </summary>
    MiddleRight,

    /// <summary>
    /// 左下。
    /// </summary>
    BottomLeft,

    /// <summary>
    /// 下中央。
    /// </summary>
    BottomCenter,

    /// <summary>
    /// 右下。
    /// </summary>
    BottomRight,
}
